package com.onlynote.app.ui

/**
 * Имя папки в интерфейсе: заглавная первая буква, остальное — как набрал человек.
 *
 * Капс на именах папок был типографским приёмом, пока папок было мало: он делал
 * строку тихой подписью. В рабочем списке капс читается как крик — он громче
 * заголовков заметок, хотя папка в иерархии старше, но по смыслу тише.
 * Поэтому капс остался только там, где он несёт смысл, а имя папки — просто имя.
 */
fun String.folderTitle(): String = replaceFirstChar { first ->
    if (first.isLowerCase()) first.titlecase() else first.toString()
}
